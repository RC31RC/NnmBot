function segmentMeaning(segment) {
  const exact = terms.get(segment) ?? terms.get(segment.toLowerCase());
  if (exact) return exact;
  if (segment.startsWith('quality__')) return '数据质量统计的' + segment.slice('quality__'.length).split('__').map(segmentMeaning).join('的');
  if (segment.includes('__')) return segment.split('__').map(segmentMeaning).join('的');
  throw new Error('缺少官方字段中文释义：' + segment);
}

function officialFieldMeaning(jsonPath) {
  const segments = (Array.isArray(jsonPath) ? jsonPath : [jsonPath])
    .filter(segment => segment && segment !== '*' && segment !== '{key}');
  return segments.map(segmentMeaning).join('的');
}

